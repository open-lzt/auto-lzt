"""The handful of filters worth showing above the fold, per category.

123 controls in one form is not a form. The canvas shows this short list first and collapses the
rest behind "Все фильтры (N)".

**Explicit data, deliberately, not a heuristic.** A rule like "promote anything whose name contains
price/origin/email" was measured against the live signatures and promoted 90 of Steam's 123 fields —
it curated nothing. Which filters matter for sniping is a judgement about the marketplace, and
judgements do not compress into a regex.

Every name here is checked against the live signature by ``test_curated_names_all_exist``, so a
pylzt rename turns this file red instead of silently dropping a control from the top of the form.
"""

