def curated_filters(category: SearchableCategory) -> tuple[str, ...]:
    """The short list for this category; the shared core when nobody has curated it yet.

    Returning the core rather than an empty tuple matters: an uncurated category would otherwise
    open with a bare "Все фильтры (58)" and no starting point at all.
    """
    return _BY_CATEGORY.get(category, _CORE)
